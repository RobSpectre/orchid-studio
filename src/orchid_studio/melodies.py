def melodic_pitch(held, interval, mode='bloom'):
    root=min(held)
    pcs={(pitch-root)%12 for pitch in held}
    minor=(3 in pcs and 4 not in pcs) or (not ({3,4}&pcs) and MELODIES[mode].get('default_minor',False))
    offset=interval[1 if minor else 0]
    pitch=root+offset
    while pitch>127:pitch-=12
    while pitch<0:pitch+=12
    return pitch
